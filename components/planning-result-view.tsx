// Shared, presentation-only rendering of a planning result (whether just
// produced by a live "Run planning" click, or reopened from a saved
// PlanningRun). No "use client" directive - this component has no hooks
// or state, so it can be rendered from a Server Component page
// (app/runs/[id]/page.tsx) as well as from within a client component
// (SprintPlanningWorkspace).

export type ScoredItemDto = {
  id: string;
  title: string;
  priority: "LOW" | "MEDIUM" | "HIGH" | "CRITICAL";
  status: "BACKLOG" | "READY" | "IN_PROGRESS" | "DONE";
  storyPoints: number | null;
  score: number;
  isBlocked: boolean;
  blockedByTitles: string[];
};

export interface PlanningResultViewProps {
  sprintContextName: string;
  generatedBy: string;
  rationaleSummary: string;
  riskFlags: string[];
  prioritizedItems: ScoredItemDto[];
  recommendedItems: ScoredItemDto[];
  excludedItems: ScoredItemDto[];
  totalRecommendedStoryPoints: number;
  createdAt?: string;
}

function ItemsTable({ items }: { items: ScoredItemDto[] }) {
  if (items.length === 0) {
    return <p className="text-sm text-zinc-500">No items.</p>;
  }

  return (
    <table className="w-full text-sm">
      <thead>
        <tr className="border-b border-zinc-200 text-left text-zinc-500">
          <th className="py-1 pr-2 font-medium">Title</th>
          <th className="py-1 pr-2 font-medium">Priority</th>
          <th className="py-1 pr-2 font-medium">Status</th>
          <th className="py-1 pr-2 font-medium">Points</th>
          <th className="py-1 pr-2 font-medium">Score</th>
          <th className="py-1 font-medium">Blocked by</th>
        </tr>
      </thead>
      <tbody>
        {items.map((item) => (
          <tr key={item.id} className="border-b border-zinc-100">
            <td className="py-1 pr-2 text-zinc-900">{item.title}</td>
            <td className="py-1 pr-2 text-zinc-600">{item.priority}</td>
            <td className="py-1 pr-2 text-zinc-600">{item.status}</td>
            <td className="py-1 pr-2 text-zinc-600">
              {item.storyPoints ?? "—"}
            </td>
            <td className="py-1 pr-2 text-zinc-600">{item.score}</td>
            <td className="py-1 text-zinc-600">
              {item.blockedByTitles.length > 0
                ? item.blockedByTitles.join(", ")
                : "—"}
            </td>
          </tr>
        ))}
      </tbody>
    </table>
  );
}

export function PlanningResultView({
  sprintContextName,
  generatedBy,
  rationaleSummary,
  riskFlags,
  prioritizedItems,
  recommendedItems,
  excludedItems,
  totalRecommendedStoryPoints,
  createdAt,
}: PlanningResultViewProps) {
  return (
    <div className="flex flex-col gap-5">
      <div>
        <h4 className="text-sm font-medium text-zinc-900">
          {sprintContextName}
        </h4>
        <p className="mt-1 text-xs text-zinc-500">
          Generated by {generatedBy}
          {createdAt && ` · ${new Date(createdAt).toLocaleString()}`} ·{" "}
          {totalRecommendedStoryPoints} recommended pts
        </p>
        <p className="mt-2 text-sm text-zinc-700">{rationaleSummary}</p>
      </div>

      {riskFlags.length > 0 && (
        <div className="rounded-md border border-amber-200 bg-amber-50 p-3">
          <h5 className="text-xs font-medium text-amber-800">Risk flags</h5>
          <ul className="mt-1 list-inside list-disc text-sm text-amber-800">
            {riskFlags.map((flag, index) => (
              <li key={index}>{flag}</li>
            ))}
          </ul>
        </div>
      )}

      <div>
        <h5 className="text-xs font-medium text-zinc-500 uppercase">
          Recommended ({recommendedItems.length})
        </h5>
        <div className="mt-2 overflow-x-auto">
          <ItemsTable items={recommendedItems} />
        </div>
      </div>

      <div>
        <h5 className="text-xs font-medium text-zinc-500 uppercase">
          Excluded ({excludedItems.length})
        </h5>
        <div className="mt-2 overflow-x-auto">
          <ItemsTable items={excludedItems} />
        </div>
      </div>

      <div>
        <h5 className="text-xs font-medium text-zinc-500 uppercase">
          Full ranking ({prioritizedItems.length})
        </h5>
        <div className="mt-2 overflow-x-auto">
          <ItemsTable items={prioritizedItems} />
        </div>
      </div>
    </div>
  );
}
